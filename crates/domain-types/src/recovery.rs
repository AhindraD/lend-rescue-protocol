use core::fmt;
use serde::{Deserialize, Serialize};

use crate::amount::TokenAmount;
use crate::risk::HealthFactor;

/// Types of supported recovery actions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum RecoveryAction {
    /// Repay debt liability using existing wallet funds
    RepayDebt = 1,
    /// Deposit additional collateral to improve health factor
    AddCollateral = 2,
    /// Withdraw collateral, swap for debt token, and extinguish liability
    SwapCollateralAndRepay = 4,
}

impl RecoveryAction {
    pub const fn bitmask(&self) -> u8 {
        *self as u8
    }

    pub fn from_bitmask(val: u8) -> Option<Self> {
        match val {
            1 => Some(RecoveryAction::RepayDebt),
            2 => Some(RecoveryAction::AddCollateral),
            4 => Some(RecoveryAction::SwapCollateralAndRepay),
            _ => None,
        }
    }

    pub fn label(&self) -> &'static str {
        match self {
            RecoveryAction::RepayDebt => "Repay Debt",
            RecoveryAction::AddCollateral => "Add Collateral",
            RecoveryAction::SwapCollateralAndRepay => "Swap Collateral & Repay",
        }
    }
}

impl fmt::Display for RecoveryAction {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.label())
    }
}

/// Detailed breakdown of candidate scoring components.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct ScoreBreakdown {
    /// Capital efficiency score (higher is better: less external funds needed)
    pub capital_efficiency: u32,
    /// Safety buffer score (higher is better: higher post-HF above minimum)
    pub safety_buffer: u32,
    /// Cost penalty (lower is better: swap fees, tx costs)
    pub fee_penalty: u32,
    /// Slippage penalty (lower is better)
    pub slippage_penalty: u32,
}

impl ScoreBreakdown {
    pub fn total_score(&self) -> u32 {
        self.capital_efficiency
            .saturating_add(self.safety_buffer)
            .saturating_sub(self.fee_penalty)
            .saturating_sub(self.slippage_penalty)
    }
}

/// Recovery candidate option generated by the recovery optimizer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecoveryCandidate {
    pub action: RecoveryAction,
    pub input_amount: TokenAmount,
    pub expected_output_amount: Option<TokenAmount>,
    pub min_output_amount: Option<TokenAmount>,
    pub debt_repaid: TokenAmount,
    pub collateral_spent: TokenAmount,
    pub collateral_added: TokenAmount,
    pub expected_fee_quote: u64,
    pub estimated_slippage_bps: u16,
    pub post_health_factor: HealthFactor,
    pub safety_buffer_bps: i64,
    pub is_feasible: bool,
    pub rejection_reason: Option<String>,
    pub score: u32,
    pub score_breakdown: ScoreBreakdown,
}
