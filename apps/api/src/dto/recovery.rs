use recovery_engine::RecoveryProposal;
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

use crate::dto::common::TokenAmountDto;

/// Request payload to quote a single recovery action.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryQuoteRequest {
    pub position_id: String,
    pub action: String,
    pub target_health_factor: Option<String>,
    pub max_debt_repayment: Option<String>,
    pub max_collateral_spend: Option<String>,
    pub max_slippage_bps: Option<u16>,
}

/// Request payload to optimize across all candidate recovery actions.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryOptimizeRequest {
    pub position_id: String,
    pub target_health_factor: Option<String>,
    pub allowed_actions: Option<Vec<String>>,
    pub max_debt_repayment: Option<String>,
    pub max_collateral_spend: Option<String>,
    pub max_slippage_bps: Option<u16>,
    pub objective: Option<String>,
}

/// Detailed candidate plan DTO generated by the recovery optimizer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryPlanDto {
    pub action: String,
    pub action_label: String,
    pub input_amount: TokenAmountDto,
    pub expected_output_amount: Option<TokenAmountDto>,
    pub min_output_amount: Option<TokenAmountDto>,
    pub debt_repaid: TokenAmountDto,
    pub collateral_spent: TokenAmountDto,
    pub collateral_added: TokenAmountDto,
    pub expected_fee_formatted: String,
    pub expected_fee_raw: String,
    pub estimated_slippage_bps: u16,
    pub post_health_factor: String,
    pub post_health_factor_scaled: u64,
    pub safety_buffer_bps: i64,
    pub is_feasible: bool,
    pub rejection_reason: Option<String>,
    pub total_cost_formatted: String,
    pub total_cost_raw: String,
    pub score: u32,
    pub score_breakdown: ScoreBreakdownDto,
}

impl RecoveryPlanDto {
    pub fn from_proposal(p: &RecoveryProposal) -> Self {
        let format_quote = |raw: u64| -> String {
            let whole = raw / 1_000_000;
            let frac = raw % 1_000_000;
            format!("{}.{:06}", whole, frac)
        };

        Self {
            action: format!("{:?}", p.action),
            action_label: p.action.label().to_string(),
            input_amount: TokenAmountDto::from_domain(&p.input_amount),
            expected_output_amount: p
                .expected_output_amount
                .as_ref()
                .map(TokenAmountDto::from_domain),
            min_output_amount: p
                .min_output_amount
                .as_ref()
                .map(TokenAmountDto::from_domain),
            debt_repaid: TokenAmountDto::from_domain(&p.debt_repaid),
            collateral_spent: TokenAmountDto::from_domain(&p.collateral_spent),
            collateral_added: TokenAmountDto::from_domain(&p.collateral_added),
            expected_fee_formatted: format_quote(p.expected_fee_quote),
            expected_fee_raw: p.expected_fee_quote.to_string(),
            estimated_slippage_bps: p.estimated_slippage_bps,
            post_health_factor: p.post_health_factor.to_decimal_string(),
            post_health_factor_scaled: p.post_health_factor.0,
            safety_buffer_bps: p.safety_buffer_bps,
            is_feasible: p.is_feasible,
            rejection_reason: p.rejection_reason.clone(),
            total_cost_formatted: format_quote(p.total_cost_quote),
            total_cost_raw: p.total_cost_quote.to_string(),
            score: p.score,
            score_breakdown: ScoreBreakdownDto {
                capital_efficiency: p.score_breakdown.capital_efficiency,
                safety_buffer: p.score_breakdown.safety_buffer,
                fee_penalty: p.score_breakdown.fee_penalty,
                slippage_penalty: p.score_breakdown.slippage_penalty,
                total_score: p.score_breakdown.total_score(),
            },
        }
    }
}

/// Breakdown of individual candidate scoring criteria.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct ScoreBreakdownDto {
    pub capital_efficiency: u32,
    pub safety_buffer: u32,
    pub fee_penalty: u32,
    pub slippage_penalty: u32,
    pub total_score: u32,
}

/// Top-level recommendation response carrying ranked recovery plans.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryRecommendationResponse {
    pub recovery_id: String,
    pub position_id: String,
    pub status: String,
    pub pre_health_factor: String,
    pub target_health_factor: String,
    pub recommended_plan: Option<RecoveryPlanDto>,
    pub alternative_plans: Vec<RecoveryPlanDto>,
    pub disclaimer: String,
    pub created_at: i64,
    pub expires_at: i64,
}
